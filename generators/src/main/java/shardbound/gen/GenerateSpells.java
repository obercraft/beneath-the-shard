package shardbound.gen;

import shardbound.Data;
import shardbound.Tex;
import shardbound.model.SpellsData;
import shardbound.model.SpellsData.Spell;

import java.io.IOException;
import java.util.List;

public final class GenerateSpells {
    private GenerateSpells() {}

    public static void run() throws IOException {
        SpellsData data = Data.load("spells.json", SpellsData.class);
        StringBuilder sb = new StringBuilder();
        sb.append("% Auto-generated by GenerateSpells --- do not edit by hand.\n\n");
        emitCircle(sb, "Circle I",
                "First Circle spells need only a starting pool. Towns sell pages for 2 Refined or 1 Cult Favor each.",
                data.circleI());
        emitCircle(sb, "Circle II",
                "Grand spells: requires Dice Pool \\D{3}{6} (level 3+). Found as mid-ring pages or deep loot.",
                data.circleII());
        emitCircle(sb, "Circle III",
                "Dire and Fell spells: pool \\D{4}{6} or \\D{5}{6} (level 6+ / 9+). Deep Gates and the Star-Grave.",
                data.circleIII());

        var out = Tex.tables("spells.tex");
        Tex.write(out, sb.toString());
        int total = data.circleI().size() + data.circleII().size() + data.circleIII().size();
        System.out.println("Wrote " + out + " with " + total + " spells");
    }

    private static void emitCircle(StringBuilder sb, String title, String intro, List<Spell> spells) {
        sb.append("\\subsubsection{").append(title).append("}\n\n");
        sb.append(intro).append("\n\n");
        sb.append("\\noindent\n{\\normalsize\n\\renewcommand{\\arraystretch}{1.35}\n");
        sb.append("\\begin{tabularx}{\\linewidth}{@{\\hspace{2pt}} >{\\raggedright\\arraybackslash}p{4.0cm} >{\\centering\\arraybackslash}p{3.2cm} >{\\raggedright\\arraybackslash}X @{}}\n");
        sb.append("  \\shardheadercell{Spell} & \\shardheadercell{Diff.} & \\shardheadercell{Effect / Overcast} \\\\\n");
        for (int i = 0; i < spells.size(); i++) {
            Spell spell = spells.get(i);
            String color = (i % 2 == 0) ? "\\rowcolor{bone}" : "\\rowcolor{ash!15}";
            String tag = spell.defensive() ? "\\defensive{} " : "";
            sb.append("  ").append(color).append(' ').append(tag)
                    .append("\\textbf{").append(Tex.esc(spell.name())).append("} & ")
                    .append(spell.diff()).append(" & ")
                    .append(spell.effect())
                    .append(" \\textit{Overcast:} ").append(spell.overcast())
                    .append(" \\\\\n");
        }
        sb.append("\\end{tabularx}\n}\n\\vspace{0.55em}\n\n");
    }
}
