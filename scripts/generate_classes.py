def is_defensive(effect: str) -> bool:
    e = effect.lower()
    for o in DEFENSIVE_OFFSETS:
        e = e.replace(o, "")
    return any(k in e for k in DEFENSIVE_KEYS)


def _trim(actions, dk: str, keep: int):
    """Keep `keep` actions of difficulty dk, preferring defensive ones, in bank order."""
    cands = [a for a in actions if a[1] == dk]
    if len(cands) <= keep:
        return cands
    defensive = [a for a in cands if is_defensive(a[2])]
    chosen = defensive[:keep]
    for a in cands:
        if len(chosen) >= keep:
            break
        if a not in chosen:
            chosen.append(a)
    return [a for a in cands if a in chosen]


def full_bank(cname: str, archetype: str):
    legacy = BANK_FN[archetype](cname) + EXTRA_BANK[cname]
    kept = []
    for dk, n in KEEP.items():
        kept.extend(_trim(legacy, dk, n))
    # restore original relative order
    kept.sort(key=legacy.index)
    return kept + POWER_BANK[cname]


def check_bank(cname: str, archetype: str):
    bank = full_bank(cname, archetype)
    names = [a[0] for a in bank]
    dupes = {n for n in names if names.count(n) > 1}
    assert not dupes, (cname, "duplicate names", dupes)
    need = {}
    for diffs in LEVEL_DIFFS.values():
        for d in diffs:
            need[d] = need.get(d, 0) + 1
    have = {}
    for _, d, _ in bank:
        have[d] = have.get(d, 0) + 1
    assert have == need, (cname, "bank mismatch", have, need)
    for name, _, effect in bank:
        assert "GM" not in effect, (cname, name, "GM reference")
    n_def = sum(1 for a in bank if is_defensive(a[2]))
    assert n_def >= MIN_DEFENSIVE, (cname, "too few defensive actions", n_def)


def pick_actions(cname: str, archetype: str, level: int, used_names: set):
    """Deal the bank out by difficulty in order; every action is used exactly once."""
    bank = full_bank(cname, archetype)
    need = LEVEL_DIFFS[level]
    chosen = []
    for dk in need:
        cands = [a for a in bank if a[1] == dk and a[0] not in used_names]
        assert cands, (cname, level, dk, "bank exhausted")
        name, _, effect = cands[0]
        used_names.add(name)
        chosen.append((name, dk, effect))
    return chosen


def emit_archetype(key: str) -> str:
    meta = CLASSES[key]
    parts = [f"\\subsection{{{meta['section']}}}", "", meta["intro"], ""]
    for cname, hook in meta["classes"]:
        check_bank(cname, key)
        parts.append(f"\\subsubsection{{{cname}}}")
        parts.append(f"\\textit{{{esc(hook)}}}")
        parts.append("")
        used_names: set = set()
        for level in range(1, 11):
            parts.append(f"\\paragraph{{Level {level}.}}")
            parts.append(r"Choose one:")
            actions = pick_actions(cname, key, level, used_names)
            parts.append(level_table(actions))
            parts.append("")
        assert len(used_names) == 50, (cname, len(used_names))
    return "\n".join(parts)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for key in ("warrior", "rogue", "mage"):
        text = emit_archetype(key)
        path = OUT / f"{key}.tex"
        path.write_text(text, encoding="utf-8")
        # count actions
        n = text.count(r"\shardheadercell{Action}")
        print(f"Wrote {path} with {n} level tables")


if __name__ == "__main__":
    main()
