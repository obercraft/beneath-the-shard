package shardbound.gen;

import shardbound.Data;
import shardbound.Tex;
import shardbound.model.EquipmentData;
import shardbound.model.EquipmentData.Armor;
import shardbound.model.EquipmentData.GearItem;
import shardbound.model.EquipmentData.PricedItem;
import shardbound.model.EquipmentData.Relic;
import shardbound.model.EquipmentData.Weapon;

import java.io.IOException;
import java.util.List;

public final class GenerateEquipment {
    private GenerateEquipment() {}

    public static void run() throws IOException {
        EquipmentData data = Data.load("equipment.yaml", EquipmentData.class);
        emitEquipment(data);
        emitRelics(data.relics());
    }

    private static void emitEquipment(EquipmentData data) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("% Auto-generated by GenerateEquipment --- do not edit by hand.\n\n");

        sb.append("\\subsubsection{Weapons}\n\n");
        openTable(sb, ">{\\raggedright\\arraybackslash}p{3.6cm} c c >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{Weapon} & \\shardheadercell{Hands} & \\shardheadercell{Price} & \\shardheadercell{Effect} \\\\\n");
        List<Weapon> weapons = data.weapons();
        for (int i = 0; i < weapons.size(); i++) {
            Weapon w = weapons.get(i);
            sb.append(row(i)).append(" \\textbf{").append(Tex.esc(w.name())).append("} & ")
                    .append(w.hands()).append(" & ").append(w.price()).append(" & ")
                    .append(w.effect()).append(" \\\\\n");
        }
        closeTable(sb);
        sb.append("Price is in \\textbf{Refined} crystals. Two-handed weapons fill the weapon and off-hand slots.\n\n");

        sb.append("\\subsubsection{Off-Hand}\n\n");
        openTable(sb, ">{\\raggedright\\arraybackslash}p{3.6cm} c >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{Item} & \\shardheadercell{Price} & \\shardheadercell{Effect} \\\\\n");
        List<PricedItem> offhand = data.offhand();
        for (int i = 0; i < offhand.size(); i++) {
            PricedItem item = offhand.get(i);
            sb.append(row(i)).append(" \\textbf{").append(Tex.esc(item.name())).append("} & ")
                    .append(item.price()).append(" & ").append(item.effect()).append(" \\\\\n");
        }
        closeTable(sb);

        sb.append("\\subsubsection{Armor}\n\n");
        openTable(sb, ">{\\raggedright\\arraybackslash}p{2.4cm} c c >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{Armor} & \\shardheadercell{Boxes} & \\shardheadercell{Price} & \\shardheadercell{Notes} \\\\\n");
        List<Armor> armor = data.armor();
        for (int i = 0; i < armor.size(); i++) {
            Armor a = armor.get(i);
            sb.append(row(i)).append(" \\textbf{").append(Tex.esc(a.name())).append("} & ")
                    .append(a.boxes()).append(" & ").append(a.price()).append(" & ")
                    .append(a.notes()).append(" \\\\\n");
        }
        closeTable(sb);

        sb.append("\\subsubsection{Gear and Consumables}\n\n");
        openTable(sb, ">{\\raggedright\\arraybackslash}p{3.4cm} c c >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{Item} & \\shardheadercell{Price} & \\shardheadercell{Type} & \\shardheadercell{Effect} \\\\\n");
        List<GearItem> gear = data.gear();
        for (int i = 0; i < gear.size(); i++) {
            GearItem g = gear.get(i);
            sb.append(row(i)).append(" \\textbf{").append(Tex.esc(g.name())).append("} & ")
                    .append(g.price()).append(" & ").append(Tex.esc(g.type())).append(" & ")
                    .append(g.effect()).append(" \\\\\n");
        }
        closeTable(sb);
        sb.append("Consumables are gone when spent. Tools stay until the text says otherwise. Use Gear is an Easy Basic Action in combat.\n");

        var out = Tex.tables("equipment.tex");
        Tex.write(out, sb.toString());
        System.out.println("Wrote " + out);
    }

    private static void emitRelics(EquipmentData.Relics relics) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("% Auto-generated by GenerateEquipment --- do not edit by hand.\n\n");
        relicTable(sb, "Common (rings E--D)", relics.common(), null);
        relicTable(sb, "Uncommon (ring C)", relics.uncommon(), "Roll on the Rare table instead.");
        relicTable(sb, "Rare (ring B)", relics.rare(),
                "Roll on the Prismatic table (1--5) or Rare again (6--20 on a second d20).");

        sb.append("\\subsubsection*{Prismatic (Star-Grave / Prismatic crystal)}\n\n");
        sb.append("Roll \\D{1}{5}, or \\D{1}{20} and use $((result-1) \\bmod 5)+1$.\n\n");
        openTable(sb, "c >{\\raggedright\\arraybackslash}p{4.2cm} >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{d5} & \\shardheadercell{Relic} & \\shardheadercell{Effect} \\\\\n");
        List<Relic> prism = relics.prismatic();
        for (int i = 0; i < prism.size(); i++) {
            Relic r = prism.get(i);
            sb.append(row(i)).append(' ').append(i + 1)
                    .append(" & \\textbf{").append(Tex.esc(r.name())).append("} & ")
                    .append(r.effect()).append(" \\\\\n");
        }
        closeTable(sb);

        var out = Tex.tables("relics.tex");
        Tex.write(out, sb.toString());
        System.out.println("Wrote " + out);
    }

    private static void relicTable(StringBuilder sb, String title, List<Relic> items, String rollup) {
        sb.append("\\subsubsection*{").append(title).append("}\n\n");
        openTable(sb, "c >{\\raggedright\\arraybackslash}p{4.0cm} >{\\raggedright\\arraybackslash}X");
        sb.append("  \\shardheadercell{d20} & \\shardheadercell{Relic} & \\shardheadercell{Effect} \\\\\n");
        for (int i = 0; i < items.size(); i++) {
            Relic r = items.get(i);
            sb.append(row(i)).append(' ').append(i + 1)
                    .append(" & \\textbf{").append(Tex.esc(r.name())).append("} & ")
                    .append(r.effect()).append(" \\\\\n");
        }
        if (rollup != null && items.size() < 20) {
            for (int d = items.size() + 1; d <= 20; d++) {
                String color = (d % 2 == 1) ? "\\rowcolor{bone}" : "\\rowcolor{ash!15}";
                sb.append("  ").append(color).append(' ').append(d).append(" & --- & ").append(rollup).append(" \\\\\n");
            }
        }
        closeTable(sb);
    }

    private static String row(int i) {
        return "  " + ((i % 2 == 0) ? "\\rowcolor{bone}" : "\\rowcolor{ash!15}");
    }

    private static void openTable(StringBuilder sb, String cols) {
        sb.append("\\noindent\n{\\normalsize\n\\renewcommand{\\arraystretch}{1.35}\n");
        sb.append("\\begin{tabularx}{\\linewidth}{@{\\hspace{2pt}} ").append(cols).append(" @{}}\n");
    }

    private static void closeTable(StringBuilder sb) {
        sb.append("\\end{tabularx}\n}\n\\vspace{0.55em}\n\n");
    }
}
